#!/usr/bin/env bash
# gate.sh —— **闸门骨架**（照抄到 <任务目录>/commands/<闸门名>.sh 再改）
#
# 闸门只回答一个问题：**现在能不能往下走**。它不做判定、不产数字。
#
# 用法：bash <任务目录>/commands/<闸门名>.sh <轮次目录>
#
# 三条纪律（照抄时别丢）：
#   1. **规则的实现只有一份**：这里不许重写判据。判据/口径的唯一落点在
#      `runtime/validate_round.py`、`<轮次>/criterion.yaml`、`config/tasks/<任务名>.yaml`。
#      闸门只负责"把它调起来 + 把退出码翻成一句人话"。
#   2. **退出码要分清谁的错**：约定/用法错 → 2；口径不全/冲突、驱动不可用 → 6（评测侧无效，
#      意味着"这一轮的分数根本不该被引用"）。**不许**用 0 表示"没查但放行"。
#   3. **不许为了绿而放松**：把比例改小、把清单改短、把判据改松，都是把"现在发现"换成"以后发现"，
#      而以后发现时算力已经花掉了。
set -euo pipefail

LP_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
round_dir="${1:-}"
if [[ -z "$round_dir" ]]; then
  echo "用法：bash <任务目录>/commands/gate.sh <轮次目录>" >&2
  exit 2
fi

# ── 要查的东西（照抄时改这一段，别改上面）──────────────────────────────────
# 例：判据里写下的口径 vs 任务配置里的口径；开关取值合法。
echo "[gate] <这条闸门查什么> —— 轮次 ${round_dir}"
rc=0
# ↓ 照抄时把下面这一行换成真正的检查（例：python3 "<任务目录>/commands/xxx_consistency.py" "$清单"）。
#   骨架阶段留着 `true`：它意味着"这条闸门什么都没查" —— 这是一句可见的实话，不是静默放行。
GATE_CMD="true"
$GATE_CMD "$round_dir" || rc=$?

case "$rc" in
  0) echo "[gate] ✓ 通过" ;;
  6) echo "[gate] ✗ 口径不全/冲突 ⇒ **评测侧无效（退出 6）**：不产生指标。" >&2 ;;
  *) echo "[gate] ✗ 约定不过（退出 ${rc}）⇒ **拒绝开跑**。" >&2 ;;
esac
exit "$rc"
